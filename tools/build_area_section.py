"""[versions/v4] Generate the multi-view map section (tabs + intros + legends) from tools/data/area-pois.json
and write it into index.html between <!-- AREA-MAP:START --> and <!-- AREA-MAP:END -->.
Run after editing the POI data:  python3 tools/build_area_section.py
"""
import html, json, os, re

HERE = os.path.dirname(__file__)
ROOT = os.path.join(HERE, '..')
data = json.load(open(os.path.join(HERE, 'data', 'area-pois.json')))
views = json.load(open(os.path.join(ROOT, 'assets', 'img', 'area-map-views.json')))
e = html.escape

TABS = [
    ('boating', 'Boating', 'canoe'),
    ('biking', 'Biking', 'bike'),
    ('snow', 'Snowmobiling', 'sled'),
    ('eat', 'Eat &amp; drink', 'mug'),
    ('golf', 'Golf', 'golf'),
    ('todo', 'Things to do', 'pine'),
]
INTRO = {
    'boating': ('At the north end of Gull Lake',
                "Cottage 9 sits between the Gull Lake Narrows and private Lost Lake, at the top of the chain. The public boat launch is right across the road, and the whole lake is yours by boat."),
    'biking': ('Bike from the door',
               "The paved Gull Lake Trail loops the lake and links through Nisswa to the 120-mile Paul Bunyan State Trail. From the cabin it's almost all trail, with one short stretch on County Road 77 until the last section is finished."),
    'snow': ('Sleds, skis &amp; the ice',
             "The Gull Lake Drifters groom about 120 miles of snowmobile trail around Nisswa and up the Paul Bunyan corridor. Gull Lake hosts one of the biggest ice-fishing contests in the world, and Mount Ski Gull and miles of cross-country trails are close by."),
    'eat': ('Our family\'s favorite spots',
            "From boat-up pizza to old-school supper clubs, these are the places we keep going back to. Stars mark our absolute favorites."),
    'golf': ('Some of the best golf in Minnesota',
             "The Classic at Madden's is ranked among America's 100 Greatest Public Courses, Deacon's Lodge is an Arnold Palmer design in Minnesota's top 20, and there are resort courses on every side of Gull Lake. Stars mark our favorites."),
    'todo': ('More to do nearby',
             "Trails next door, races at BIR, state parks and Nisswa's shops. Here's what's close to the cabin."),
}
NOTE = {
    'boating': '<p class="hand">Boat right into downtown Nisswa →</p>',
    'biking': '',
    'snow': '<p class="fine">Trail conditions change daily. Check the official trail maps linked above before heading out.</p>',
    'eat': '<p class="fine">Hours change with the seasons, so check before you go.</p>',
    'golf': '',
    'todo': '',
}

def item(layer, i, p):
    num = str(p.get('num', i))
    tags = ''
    if p.get('boat'): tags += '<em class="dock">boat-in</em>'
    if p.get('pick'): tags += '<em class="pick-tag">★ our pick</em>'
    desc = f'<small>{e(p["desc"])}</small>' if p.get('desc') else ''
    link = f' <a class="poi-link" href="{e(p["url"])}" target="_blank" rel="noopener">site ↗</a>' if p.get('url') else ''
    attrs = f' data-poi="{layer}-{num}" tabindex="0"' if p.get('lat') is not None else ''
    if p.get('zoom'): attrs += f' data-zoom="{p["zoom"]}"'
    cls = ' class="legend-star"' if p.get('star') else ''
    return f'<li{attrs}{cls}><b>{num}</b>{e(p["name"])} {tags}{link}{desc}</li>'

parts = ['<!-- AREA-MAP:START (generated by tools/build_area_section.py) -->',
         '<section id="map" class="section map-section area-section">',
         '  <div class="wrap">',
         '    <div class="section-head"><p class="eyebrow">Explore from the cabin</p><h2>Your map of the lake &amp; beyond</h2></div>',
         '    <div class="map-tabs" role="tablist" aria-label="Map views">']
for i, (k, label, icon) in enumerate(TABS):
    sel = 'true' if i == 0 else 'false'
    parts.append(f'      <button role="tab" id="mt-{k}" aria-controls="mv-{k}" aria-selected="{sel}" data-map-view="{k}"{"" if i == 0 else " tabindex=\"-1\""}>'
                 f'<svg class="ico" aria-hidden="true"><use href="#i-{icon}"/></svg>{label}</button>')
parts.append('    </div>')
parts.append('    <div class="map-grid">')
parts.append('      <div class="map-copy">')
for i, (k, label, icon) in enumerate(TABS):
    title, intro = INTRO[k]
    hidden = '' if i == 0 else ' hidden'
    parts.append(f'        <div class="map-view-copy" role="tabpanel" id="mv-{k}" aria-labelledby="mt-{k}"{hidden}>')
    parts.append(f'          <h3 class="map-view-title">{title}</h3><p>{intro}</p>')
    extra = data.get(k + '_links') or []
    if extra:
        parts.append('          <p class="map-links">' + ' · '.join(f'<a href="{e(l["url"])}" target="_blank" rel="noopener">{e(l["label"])} ↗</a>' for l in extra) + '</p>')
    parts.append('          <ol class="map-legend">')
    if k == 'boating':
        parts.append('            <li data-poi="boating-L" tabindex="0" class="legend-launch"><b><svg class="ico" aria-hidden="true"><use href="#i-launch"/></svg></b>Public boat launch, across the road <small>Gull Lake Narrows Landing, right next to Zorbaz. Bring your own boat; the resort has docks for guests\' boats and a spot for your trailer.</small></li>')
    for j, p in enumerate(data.get(k, []), 1):
        parts.append('            ' + item(k, j, p))
    if k == 'boating':
        parts.append('            <li class="legend-route" aria-hidden="true"><i></i>Boat route through the chain to Nisswa <small>(approximate)</small></li>')
    if k == 'biking':
        parts.append('            <li class="legend-route legend-trail" aria-hidden="true"><i></i>Gull Lake Trail &amp; Paul Bunyan Trail</li>')
    if k == 'snow':
        parts.append('            <li class="legend-route legend-snow" aria-hidden="true"><i></i>Mapped snowmobile trails (partial, see official maps)</li>')
    parts.append('          </ol>')
    if NOTE[k]: parts.append('          ' + NOTE[k])
    parts.append('        </div>')
parts.append('      </div>')
parts.append('      <figure class="map-frame">')
parts.append('        <div class="map-zoom" role="group" aria-label="Boating map view"><button data-sub="boating" aria-pressed="true">Whole lake</button><button data-sub="north" aria-pressed="false">North end + Nisswa</button></div>')
parts.append(f'        <div class="map-holder" data-src="../../assets/img/area-map.svg" data-views=\'{json.dumps(views)}\'><p class="map-loading">Loading map…</p></div>')
parts.append('        <figcaption>Illustrated map. Locations are approximate. Map data © OpenStreetMap contributors.</figcaption>')
parts.append('      </figure>')
parts.append('    </div>')
parts.append('  </div>')
parts.append('</section>')
parts.append('<!-- AREA-MAP:END -->')
section = '\n'.join(parts)

page = os.path.join(ROOT, 'versions', 'v4', 'index.html')
s = open(page).read()
if '<!-- AREA-MAP:START' in s:
    s = re.sub(r'<!-- AREA-MAP:START.*?<!-- AREA-MAP:END -->', lambda m: section, s, flags=re.S)
else:  # first run: replace the old single-view map section
    s = re.sub(r'<!-- ============ MAP ============ -->\s*<section id="map".*?</section>', lambda m: '<!-- ============ MAP ============ -->\n' + section, s, count=1, flags=re.S)
open(page, 'w').write(s)
print('ok', len(section))
